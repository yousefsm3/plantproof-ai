"""Shift handover summaries built from templates (no LLM).

The summary is assembled only from engine findings, the cost estimate and the
analyst's own notes, so every statement can be traced back to records.
Use role names (e.g. "Night shift lead"), not personal names: the demo app is
public.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any

from .cost_model import CostEstimate, format_money
from .domain import AnalysisResult

MAX_NOTES = 2000


@dataclass
class Handover:
    scenario_id: str
    scenario_title: str
    asset: str
    shift: str
    outgoing: str
    incoming: str
    created_at: str
    status_line: str
    leading_hypothesis: dict[str, Any] | None
    contradictions: list[dict[str, Any]]
    missing_evidence: list[dict[str, Any]]
    actions: list[str]
    cost: dict[str, Any] | None
    whatif_notes: list[str] = field(default_factory=list)
    notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        return dict(self.__dict__)

    def to_json(self) -> str:
        return json.dumps(self.to_dict(), indent=2, ensure_ascii=False)

    def to_markdown(self) -> str:
        lines = [
            f"# Shift handover - {self.asset}",
            "",
            f"- **Scenario:** {self.scenario_title}",
            f"- **Shift:** {self.shift}",
            f"- **From:** {self.outgoing or '-'}  →  **To:** {self.incoming or '-'}",
            f"- **Generated:** {self.created_at}",
            "",
            "## Status",
            self.status_line,
            "",
        ]
        if self.leading_hypothesis:
            h = self.leading_hypothesis
            lines += ["## Leading hypothesis",
                      f"**{h['name']}** - confidence {h['confidence']:.0%} ({h['label']}). "
                      f"Evidence records: {', '.join(h['record_ids'][:8]) or '-'}"
                      + (" …" if len(h["record_ids"]) > 8 else ""), ""]
        lines.append("## Contradictions to resolve")
        if self.contradictions:
            for c in self.contradictions:
                lines.append(f"- [{c['finding_id']}] {c['title']} - records "
                             f"{', '.join(c['record_ids'][:4])}"
                             + (" …" if len(c["record_ids"]) > 4 else ""))
        else:
            lines.append("- None detected")
        lines += ["", "## Missing evidence"]
        if self.missing_evidence:
            for m in self.missing_evidence:
                lines.append(f"- [{m['finding_id']}] {m['title']} - {m['detail']}")
        else:
            lines.append("- None")
        lines += ["", "## Actions for incoming shift"]
        lines += [f"{i}. {a}" for i, a in enumerate(self.actions, start=1)] or ["- None"]
        if self.cost:
            c = self.cost
            lines += ["", "## Cost impact (illustrative)",
                      f"{c['hypothesis']}: low {c['low']}, base {c['base']}, high {c['high']}."]
        if self.whatif_notes:
            lines += ["", "## What If notes"] + [f"- {n}" for n in self.whatif_notes]
        if self.notes:
            lines += ["", "## Analyst notes", self.notes]
        lines += ["", "---",
                  "_Generated by PlantProof AI from synthetic demo data. "
                  "Every finding is traceable to the listed record IDs._", ""]
        return "\n".join(lines)


def build_handover(analysis: AnalysisResult, scenario_meta: dict[str, Any], *,
                   shift: str, outgoing: str = "", incoming: str = "", notes: str = "",
                   cost: CostEstimate | None = None, whatif_notes: list[str] | None = None,
                   now: datetime | None = None) -> Handover:
    now = now or datetime.now(timezone.utc)
    top = analysis.top
    n_c, n_m = len(analysis.contradictions), len(analysis.missing)
    if top is None:
        status = "No hypotheses evaluated."
    else:
        status = (f"Investigation open. Leading hypothesis: {top.name} "
                  f"({top.confidence:.0%}, {top.confidence_label}). "
                  f"{n_c} contradiction(s) and {n_m} missing evidence item(s) outstanding.")

    actions: list[str] = []
    for c in analysis.contradictions:
        actions.append(f"Resolve {c.finding_id} ({c.title.lower()}): re-check record "
                       f"{c.key} against the conflicting data.")
    for m in analysis.missing:
        actions.append(f"Collect {m.title.lower()} ({m.finding_id}).")
    if top is not None and top.confidence_label != "Low":
        actions += list(top.recommended_actions)

    cost_dict = None
    if cost is not None:
        t, s = cost.totals, cost.currency_symbol
        cost_dict = {"hypothesis_id": cost.hypothesis_id,
                     "hypothesis": next((a.name for a in analysis.assessments
                                         if a.hypothesis_id == cost.hypothesis_id),
                                        cost.hypothesis_id),
                     "low": format_money(t["low"], s), "base": format_money(t["base"], s),
                     "high": format_money(t["high"], s)}

    return Handover(
        scenario_id=analysis.scenario_id,
        scenario_title=scenario_meta.get("title", analysis.scenario_id),
        asset=scenario_meta.get("asset_name", scenario_meta.get("asset_id", "")),
        shift=shift.strip()[:80],
        outgoing=outgoing.strip()[:80],
        incoming=incoming.strip()[:80],
        created_at=now.strftime("%Y-%m-%d %H:%M UTC"),
        status_line=status,
        leading_hypothesis=None if top is None else {
            "id": top.hypothesis_id, "name": top.name, "confidence": top.confidence,
            "label": top.confidence_label, "record_ids": top.record_ids},
        contradictions=[c.to_dict() for c in analysis.contradictions],
        missing_evidence=[m.to_dict() for m in analysis.missing],
        actions=actions,
        cost=cost_dict,
        whatif_notes=list(whatif_notes or []),
        notes=notes.strip()[:MAX_NOTES],
    )
